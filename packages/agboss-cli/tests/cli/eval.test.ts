/**
 * #396 PR 2 — `agboss eval` as subcommands (S4): `eval run` (an eval suite, k runs, the artifact),
 * `eval score` (the bare `agboss eval` before), the bare `agboss eval` listing them; `agboss check`
 * checks the application's eval suites (Loop 0). The fixture's models answer through a transport
 * provider: no key, no network.
 */
import { mkdirSync, mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { envelope, agboss } from "./agboss.js";

/** The framework's fixture (its types generated by check:types): its suites in eval-suites/ next to it. */
const APPLICATION = new URL("../../../agboss/tests/flow/fixtures/evals.fixture.ts", import.meta.url)
  .pathname;
const CWD = mkdtempSync(join(tmpdir(), "agboss-eval-"));
const RUN = ["eval", "run", "--application", APPLICATION] as const;

interface EvalRunResult {
  readonly kind: string;
  readonly suite: string;
  readonly runs: number;
  readonly cases: readonly { name: string; passed: number; passAtK: boolean; passHatK: boolean }[];
}

describe("#396 PR 2: agboss eval is made of subcommands", () => {
  it("the bare agboss eval prints its subcommands and exits 2", async () => {
    const call = await agboss(["eval"], CWD);

    expect(call.code).toBe(2);
    expect(call.stdout).toContain("Subcommands:");
    expect(call.stdout).toContain("agboss eval run [--suite <name>]");
    expect(call.stdout).toContain("agboss eval score [--start <name>]");
    expect(call.stderr).toContain("expected agboss eval run | score | show");
  });

  it("with --json: one envelope, usage.missing-argument", async () => {
    const call = await agboss(["eval", "--json"], CWD);

    expect(call.code).toBe(2);
    expect(envelope(call)).toMatchObject({
      ok: false,
      command: "eval",
      error: { code: "usage.missing-argument" },
    });
  });

  it("an unknown subcommand names the known ones", async () => {
    const call = await agboss(["eval", "rerun"], CWD);

    expect(call.code).toBe(2);
    expect(call.stderr).toContain(
      'unknown subcommand "eval rerun" — expected eval run | score | show',
    );
  });

  it("each subcommand has its own help and options", async () => {
    const help = await agboss(["eval", "run", "--help"], CWD);
    const machine = await agboss(["help", "eval", "--json"], CWD);

    expect(help.stdout).toContain("--runs <k>");
    expect(help.stdout).not.toContain("--limit");
    const described = envelope(machine).result as { subcommands: { name: string }[] };
    expect(described.subcommands.map((sub) => sub.name)).toEqual([
      "eval run",
      "eval score",
      "eval show",
      "eval calibrate",
      "eval ui",
    ]);
  });

  it("an option of the other subcommand is unknown", async () => {
    const call = await agboss([...RUN, "--limit", "3"], CWD);

    expect(call.code).toBe(2);
    expect(call.stderr).toContain("unknown option --limit — see agboss help eval run");
  });

  it("eval score is today's scoring of recorded runs", async () => {
    const call = await agboss(["eval", "score", "--application", APPLICATION, "--json"], CWD);

    expect(call.code).toBe(0);
    expect(envelope(call)).toMatchObject({
      ok: true,
      command: "eval",
      result: { report: { scored: 0 }, summary: [] },
    });
  });
});

describe("#396 PR 2: agboss eval run", () => {
  it("several suites and no --suite: exit 2, the suites listed", async () => {
    const call = await agboss([...RUN], CWD);

    expect(call.code).toBe(2);
    expect(call.stderr).toContain(
      "the application has 2 eval suites: name one with --suite — its suites (eval-suites/*.eval-suite.ts): broken-eval-suite, desk-eval-suite",
    );
  });

  it("an unknown suite: eval.unknown-suite", async () => {
    const call = await agboss([...RUN, "--suite", "desks-eval-suite", "--json"], CWD);

    expect(call.code).toBe(2);
    expect(envelope(call)).toMatchObject({ error: { code: "eval.unknown-suite" } });
  });

  it("--runs below 1 is a usage error", async () => {
    const call = await agboss([...RUN, "--suite", "desk-eval-suite", "--runs", "0"], CWD);

    expect(call.code).toBe(2);
    expect(call.stderr).toContain('option --runs needs a whole number from 1, got "0"');
  });

  it("a suite that does not assemble: exit 3, its rule", async () => {
    const call = await agboss([...RUN, "--suite", "broken-eval-suite", "--json"], CWD);

    expect(call.code).toBe(3);
    expect(envelope(call)).toMatchObject({ error: { code: "graph.rules" } });
  });

  it("runs every case k times: the table, the totals, the artifact", async () => {
    const report = join(CWD, "eval", "run.json");
    const call = await agboss(
      [...RUN, "--suite", "desk-eval-suite", "--runs", "2", "--report", report],
      CWD,
    );

    expect(call.code).toBe(0);
    const lines = call.stdout.split("\n");
    expect(lines[0]).toMatch(
      /^desk-eval-suite · lookup-workflow 1\.0\.0 · config \w{6} · 2 cases × 2 runs · env dev$/,
    );
    expect(lines.slice(1, 4)).toEqual([
      "case              pass@2  pass^2  runs  first failure",
      "looks-order-7-up  yes     yes     ✓✓",
      'looks-order-8-up  no      no      ✗✗    run 1: trajectory: lookup-tool not called with {"orderId":"8"} (required; 1 call(s))',
    ]);
    expect(lines[4]).toMatch(
      /^pass@2 1\/2 · pass\^2 1\/2 · unstable 0 · judge calls 2 \(2 skipped by the cascade\) · spent \$\d+\.\d{4}$/,
    );
    expect(lines[5]).toBe(`report → ${report}`);
    const written = JSON.parse(readFileSync(report, "utf8")) as EvalRunResult;
    expect(written).toMatchObject({ kind: "agboss.eval-run", suite: "desk-eval-suite", runs: 2 });
  });

  it("--json: the artifact is the envelope's result, the file in created", async () => {
    const report = join(CWD, "run.json");
    const call = await agboss(
      [...RUN, "--suite", "desk-eval-suite", "--report", report, "--json"],
      CWD,
    );

    expect(call.code).toBe(0);
    const found = envelope(call);
    expect(found).toMatchObject({ ok: true, command: "eval", created: [report] });
    const result = found.result as EvalRunResult;
    expect(result.cases.map((each) => [each.name, each.passAtK, each.passHatK])).toEqual([
      ["looks-order-7-up", true, true],
      ["looks-order-8-up", false, false],
    ]);
  });
});

describe("#396 PR 2: agboss check checks the eval suites (Loop 0)", () => {
  it("a suite's rule is a problem of its file; the checks name eval-suites", async () => {
    const call = await agboss(["check", "--application", APPLICATION, "--json"], CWD);

    expect(call.code).toBe(3);
    const result = envelope(call).result as {
      checks: readonly string[];
      problems: readonly { file: string; code: string }[];
    };
    expect(result.checks).toContain("eval-suites");
    expect(result.problems).toEqual([
      expect.objectContaining({
        file: expect.stringMatching(/eval-suites\/broken\.eval-suite\.ts$/) as unknown,
        code: "eval.duplicate-case",
      }),
    ]);
  });
});

/** A baseline made from a real run: the run's artifact with some cases' outcomes set. */
interface BaselineCase {
  name: string;
  caseHash: string;
  passed: number;
  runs: number;
  passAtK: boolean;
  passHatK: boolean;
  isUnstable: boolean;
}

async function baselineWith(file: string, edit: (cases: BaselineCase[]) => void): Promise<string> {
  const path = join(CWD, file);
  await agboss([...RUN, "--suite", "desk-eval-suite", "--runs", "2", "--report", path], CWD);
  const written = JSON.parse(readFileSync(path, "utf8")) as { cases: BaselineCase[] };
  edit(written.cases);
  writeFileSync(path, JSON.stringify(written));
  return path;
}

/** The second case (it fails every run) as if it had passed every run on the baseline. */
const stableOnBaseline = (cases: BaselineCase[]): void => {
  Object.assign(cases[1] ?? {}, { passed: 2, passAtK: true, passHatK: true, isUnstable: false });
};

describe("#396 PR 3: agboss eval run --baseline", () => {
  it("each case against the baseline; without --fail-on-regression a regression exits 0", async () => {
    const baseline = await baselineWith("stable.json", stableOnBaseline);
    const call = await agboss(
      [...RUN, "--suite", "desk-eval-suite", "--runs", "2", "--baseline", baseline],
      CWD,
    );

    expect(call.code).toBe(0);
    expect(call.stdout).toContain(
      [
        "case              baseline  candidate  verdict",
        "looks-order-7-up  2/2       2/2        unchanged",
        "looks-order-8-up  2/2       0/2        regressed",
        "1 regressed · 1 unchanged",
      ].join("\n"),
    );
  });

  it("--save-baseline writes a compact git-friendly baseline snapshot that --baseline compares against", async () => {
    const baselinePath = join(CWD, "compact-baseline.json");
    const saveCall = await agboss(
      [...RUN, "--suite", "desk-eval-suite", "--runs", "2", "--save-baseline", baselinePath],
      CWD,
    );
    expect(saveCall.code).toBe(0);
    const snapshot = JSON.parse(readFileSync(baselinePath, "utf8")) as {
      kind: string;
      schemaVersion: number;
      cases: {
        caseId: string;
        caseHash: string;
        runs: number;
        passed: number;
        passAtK: boolean;
        passHatK: boolean;
        flaky: boolean;
        avgSpendUsd: number;
        verdictSummary: string;
      }[];
    };
    expect(snapshot.kind).toBe("agboss.eval-baseline");
    expect(snapshot.schemaVersion).toBe(1);
    expect(snapshot.cases).toHaveLength(2);
    expect(snapshot.cases[0]).toMatchObject({
      caseId: "looks-order-7-up",
      runs: 2,
      passed: 2,
      passAtK: true,
      passHatK: true,
      flaky: false,
    });
    expect(snapshot.cases[0]?.verdictSummary).toContain("2/2 passed");

    // Edit case 2 in the compact baseline to simulate a previously passing case and verify regression gate
    Object.assign(snapshot.cases[1] ?? {}, {
      passed: 2,
      passAtK: true,
      passHatK: true,
      flaky: false,
    });
    writeFileSync(baselinePath, JSON.stringify(snapshot, null, 2));

    const compareCall = await agboss(
      [
        ...RUN,
        "--suite",
        "desk-eval-suite",
        "--runs",
        "2",
        "--baseline",
        baselinePath,
        "--fail-on-regression",
      ],
      CWD,
    );
    expect(compareCall.code).toBe(5);
    expect(compareCall.stdout).toContain("looks-order-8-up  2/2       0/2        regressed");
  });

  it("--fail-on-regression: exit 5, eval.regressed naming the cases", async () => {
    const baseline = await baselineWith("gate.json", stableOnBaseline);
    const call = await agboss(
      [
        ...RUN,
        "--suite",
        "desk-eval-suite",
        "--runs",
        "2",
        "--baseline",
        baseline,
        "--fail-on-regression",
        "--json",
      ],
      CWD,
    );

    expect(call.code).toBe(5);
    const found = envelope(call);
    expect(found).toMatchObject({
      ok: false,
      error: {
        code: "eval.regressed",
        message: `1 case regressed against ${baseline}: looks-order-8-up`,
      },
    });
    const result = found.result as { baseline: { regressed: readonly string[] } };
    expect(result.baseline.regressed).toEqual(["looks-order-8-up"]);
  });

  it("a case that flapped on the baseline is quarantined: never a failure", async () => {
    const baseline = await baselineWith("flaky.json", (cases) => {
      Object.assign(cases[1] ?? {}, {
        passed: 1,
        passAtK: true,
        passHatK: false,
        isUnstable: true,
      });
    });
    const call = await agboss(
      [
        ...RUN,
        "--suite",
        "desk-eval-suite",
        "--runs",
        "2",
        "--baseline",
        baseline,
        "--fail-on-regression",
      ],
      CWD,
    );

    expect(call.code).toBe(0);
    expect(call.stdout).toContain(
      "looks-order-8-up  1/2       0/2        flaky-on-baseline (quarantined)",
    );
    expect(call.stdout).toContain("1 unchanged · 1 quarantined");
  });

  it("a case whose definition changed is not compared", async () => {
    const baseline = await baselineWith("changed.json", (cases) => {
      stableOnBaseline(cases);
      Object.assign(cases[1] ?? {}, { caseHash: "0000000000000000" });
    });
    const call = await agboss(
      [
        ...RUN,
        "--suite",
        "desk-eval-suite",
        "--runs",
        "2",
        "--baseline",
        baseline,
        "--fail-on-regression",
      ],
      CWD,
    );

    expect(call.code).toBe(0);
    expect(call.stdout).toContain("looks-order-8-up  2/2       0/2        changed (not compared)");
  });

  it("a file that is no run artifact: exit 2, eval.run-invalid, before anything runs", async () => {
    const path = join(CWD, "not-a-run.json");
    writeFileSync(path, JSON.stringify({ kind: "agboss.eval-run", schemaVersion: 5 }));
    const call = await agboss(
      [...RUN, "--suite", "desk-eval-suite", "--baseline", path, "--json"],
      CWD,
    );

    expect(call.code).toBe(2);
    expect(envelope(call)).toMatchObject({
      error: {
        code: "eval.run-invalid",
        message: `${path} is not a run artifact this agboss reads: schemaVersion 5 — this agboss reads 1 to 4`,
      },
    });
  });

  it("--fail-on-regression needs --baseline", async () => {
    const call = await agboss([...RUN, "--suite", "desk-eval-suite", "--fail-on-regression"], CWD);

    expect(call.code).toBe(2);
    expect(call.stderr).toContain("--fail-on-regression needs --baseline");
  });

  it("--profile runs the suite on a profile of the workflow (profiles/<workflow>/<name>.yaml)", async () => {
    mkdirSync(join(CWD, "profiles", "lookup-workflow"), { recursive: true });
    writeFileSync(
      join(CWD, "profiles", "lookup-workflow", "next.yaml"),
      "profile: next\nversion: 1.0.0-next\n",
    );
    const call = await agboss(
      [...RUN, "--suite", "desk-eval-suite", "--profile", "next", "--json"],
      CWD,
    );

    expect(call.code).toBe(0);
    const result = envelope(call).result as { workflow: { version: string } };
    expect(result.workflow.version).toBe("1.0.0-next");
  });
});

describe("#396 PR 6: agboss eval run --chaos", () => {
  const SUITE = [...RUN, "--suite", "desk-eval-suite"] as const;

  it("every model call fails as told: the runs fail, the artifact says what was injected", async () => {
    const call = await agboss(
      [
        ...SUITE,
        "--runs",
        "2",
        "--chaos",
        "1",
        "--chaos-seed",
        "7",
        "--chaos-failures",
        "rate-limited",
        "--json",
      ],
      CWD,
    );

    expect(call.code).toBe(0);
    const result = envelope(call).result as {
      cases: readonly { passed: number }[];
      chaos: {
        rate: number;
        seed: number;
        failures: string[];
        calls: number;
        injected: Record<string, number>;
      };
    };
    expect(result.cases.map((found) => found.passed)).toEqual([0, 0]);
    expect(result.chaos).toMatchObject({
      rate: 1,
      seed: 7,
      failures: ["rate-limited"],
      injected: { "rate-limited": result.chaos.calls, timeout: 0, "truncated-response": 0 },
    });
    expect(result.chaos.calls).toBeGreaterThan(0);
  });

  it("prints what it injected; the same seed injects the same failures", async () => {
    const args = [...SUITE, "--chaos", "0.5", "--chaos-seed", "11"] as const;
    const first = await agboss(args, CWD);
    const second = await agboss(args, CWD);
    const line = (stdout: string) => stdout.split("\n").find((each) => each.startsWith("chaos: "));

    expect(first.code).toBe(0);
    expect(line(first.stdout)).toMatch(
      /^chaos: rate 0\.5, seed 11 — \d+ of \d+ model calls failed on purpose \(rate-limited \d+, timeout \d+, truncated-response \d+\)$/,
    );
    expect(line(second.stdout)).toBe(line(first.stdout));
  });

  it("the rate and the seed come together; the values are checked", async () => {
    const noSeed = await agboss([...SUITE, "--chaos", "0.2", "--json"], CWD);
    const noRate = await agboss([...SUITE, "--chaos-seed", "3", "--json"], CWD);
    const badRate = await agboss([...SUITE, "--chaos", "2", "--chaos-seed", "3", "--json"], CWD);
    const badFailure = await agboss(
      [...SUITE, "--chaos", "0.2", "--chaos-seed", "3", "--chaos-failures", "outage", "--json"],
      CWD,
    );

    expect([noSeed.code, noRate.code, badRate.code, badFailure.code]).toEqual([2, 2, 2, 2]);
    expect(envelope(noSeed)).toMatchObject({ error: { code: "usage.missing-option" } });
    expect(envelope(noRate)).toMatchObject({
      error: {
        code: "usage.missing-option",
        message: expect.stringContaining("--chaos-seed needs --chaos <rate>") as unknown,
      },
    });
    expect(envelope(badRate)).toMatchObject({ error: { code: "usage.option-value" } });
    expect(envelope(badFailure)).toMatchObject({
      error: {
        code: "usage.option-value",
        message: expect.stringContaining("rate-limited, timeout, truncated-response") as unknown,
      },
    });
  });
});

describe("#396 PR 7: agboss eval run --metamorphic", () => {
  const SUITE = [...RUN, "--suite", "desk-eval-suite"] as const;

  it("a case's variants run too, as the check metamorphic; a case without variants has none", async () => {
    const call = await agboss([...SUITE, "--metamorphic", "--json"], CWD);

    expect(call.code).toBe(0);
    const result = envelope(call).result as {
      metamorphic: boolean;
      cases: readonly {
        name: string;
        runResults: readonly { checks: readonly { check: string; status: string }[] }[];
      }[];
    };
    expect(result.metamorphic).toBe(true);
    const checksOf = (name: string) =>
      result.cases
        .find((found) => found.name === name)
        ?.runResults[0]?.checks.map((check) => [check.check, check.status]);
    expect(checksOf("looks-order-7-up")).toEqual([
      ["trajectory", "passed"],
      ["quotes-lookup-judge", "passed"],
      ["metamorphic", "passed"],
    ]);
    expect(checksOf("looks-order-8-up")?.map(([check]) => check)).not.toContain("metamorphic");
  });

  it("without the flag the artifact says nothing of it", async () => {
    const call = await agboss([...SUITE, "--json"], CWD);

    expect(call.code).toBe(0);
    expect(envelope(call).result).not.toHaveProperty("metamorphic");
  });
});
